import { formatTime, formatDate } from './time.js';
import { getSliceCues, SLICE_TAGS } from './slices.js';

function sanitizeMarkdownLine(value) {
  return String(value || '').replace(/\r?\n/g, ' ').trim();
}

export function buildCourseMarkdown(course, slices, subtitles) {
  const exportedAt = new Date();
  const total = slices.length;
  const done = slices.filter((slice) => slice.tag === 'done').length;
  const reviewed = slices.filter((slice) => slice.tag === 'review').length;
  const hard = slices.filter((slice) => slice.tag === 'hard').length;

  const lines = [
    `# ${sanitizeMarkdownLine(course?.name || '未命名课程')}`,
    '',
    '> 由「课隙」本地学习工作台导出 · 视频与学习记录仅保存在你的设备',
    '',
    '| 项目 | 内容 |',
    '| --- | --- |',
    `| 来源文件 | ${sanitizeMarkdownLine(course?.fileName || '未记录')} |`,
    `| 课程时长 | ${formatTime(course?.duration || 0, { hours: 'auto' })} |`,
    `| 切片进度 | ${done} / ${total} 已掌握 |`,
    `| 标签统计 | 待回看 ${reviewed} · 重难点 ${hard} |`,
    `| 导出日期 | ${formatDate(exportedAt.getTime())} |`,
    '',
    '---',
    '',
  ];

  slices.forEach((slice, index) => {
    const tag = SLICE_TAGS[slice.tag] ?? SLICE_TAGS.review;
    const cues = getSliceCues(slice, subtitles);

    lines.push(
      `## ${String(index + 1).padStart(2, '0')} · ${formatTime(slice.startTime)} – ${formatTime(slice.endTime)}`,
      '',
      `**标签**：${tag.label}`,
      '',
      `**切片标题**：${sanitizeMarkdownLine(slice.title)}`,
      '',
    );

    if (cues.length) {
      lines.push('### 字幕', '');
      cues.forEach((cue) => {
        lines.push(`- \`${formatTime(cue.start)}\` ${sanitizeMarkdownLine(cue.text)}`);
      });
      lines.push('');
    } else {
      lines.push('### 字幕', '', '_本段没有匹配到字幕。_', '');
    }

    lines.push('### 笔记', '');
    const note = String(slice.note || '').trim();
    lines.push(note || '_暂无笔记。_', '', '---', '');
  });

  lines.push('', `_Generated by 课隙 · ${exportedAt.toISOString()}_`, '');
  return lines.join('\n');
}

export function markdownFileName(courseName, date = new Date()) {
  const stamp = [
    date.getFullYear(),
    String(date.getMonth() + 1).padStart(2, '0'),
    String(date.getDate()).padStart(2, '0'),
  ].join('-');
  const safeName = String(courseName || '课程')
    .replace(/[\\/:*?"<>|]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 60);
  return `${safeName || '课程'}_学习笔记_${stamp}.md`;
}
